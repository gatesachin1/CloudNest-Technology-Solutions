// Local production preview: serves /out and runs the SAME CloudFront Function
// used in production (infra/cloudfront/viewer-request.js), so redirects and
// clean URLs can be tested locally. Usage: npm run build && npm start
import fs from "node:fs";
import http from "node:http";
import path from "node:path";
import zlib from "node:zlib";

const root = path.resolve("out");
const port = Number(process.env.PORT ?? 3000);

const fnSource = fs.readFileSync(path.resolve("infra/cloudfront/viewer-request.js"), "utf8");
const handler = new Function(`${fnSource}; return handler;`)();

const types = {
  ".html": "text/html; charset=utf-8",
  ".js": "text/javascript; charset=utf-8",
  ".css": "text/css; charset=utf-8",
  ".json": "application/json",
  ".txt": "text/plain; charset=utf-8",
  ".xml": "application/xml",
  ".svg": "image/svg+xml",
  ".png": "image/png",
  ".jpg": "image/jpeg",
  ".webp": "image/webp",
  ".ico": "image/x-icon",
  ".woff2": "font/woff2",
};
// Extension-less files generated by Next (OG images). Upload with the same types in production.
const extensionless = { "/opengraph-image": "image/png", "/twitter-image": "image/png" };

if (!fs.existsSync(root)) {
  console.error("No /out folder. Run `npm run build` first.");
  process.exit(1);
}

http
  .createServer((req, res) => {
    const url = new URL(req.url ?? "/", "http://localhost");
    const querystring = {};
    for (const [k, v] of url.searchParams) querystring[k] = { value: v };
    const result = handler({
      request: { uri: decodeURIComponent(url.pathname), querystring, headers: { host: { value: req.headers.host ?? "" } } },
    });

    if (result.statusCode) {
      res.writeHead(result.statusCode, { Location: result.headers.location.value });
      return res.end();
    }

    const file = path.join(root, path.normalize(result.uri));
    if (!file.startsWith(root) || !fs.existsSync(file) || fs.statSync(file).isDirectory()) {
      res.writeHead(404, { "Content-Type": types[".html"] });
      return fs.createReadStream(path.join(root, "404.html")).pipe(res);
    }
    const type = extensionless[result.uri] ?? types[path.extname(file)] ?? "application/octet-stream";
    // Mirror CloudFront: compress text and cache hashed assets for a year.
    const headers = {
      "Content-Type": type,
      "Cache-Control": result.uri.startsWith("/_next/static/") ? "public, max-age=31536000, immutable" : "public, max-age=0, must-revalidate",
    };
    const compressible = /^(text\/|application\/(json|xml)|image\/svg)/.test(type);
    if (compressible && /\bbr\b/.test(req.headers["accept-encoding"] ?? "")) {
      res.writeHead(200, { ...headers, "Content-Encoding": "br", Vary: "Accept-Encoding" });
      return fs.createReadStream(file).pipe(zlib.createBrotliCompress({ params: { [zlib.constants.BROTLI_PARAM_QUALITY]: 5 } })).pipe(res);
    }
    if (compressible && /\bgzip\b/.test(req.headers["accept-encoding"] ?? "")) {
      res.writeHead(200, { ...headers, "Content-Encoding": "gzip", Vary: "Accept-Encoding" });
      return fs.createReadStream(file).pipe(zlib.createGzip()).pipe(res);
    }
    res.writeHead(200, headers);
    fs.createReadStream(file).pipe(res);
  })
  .listen(port, () => console.log(`Preview (production routing) on http://localhost:${port}`));
